CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'DRIVER' CHECK (role IN ('ADMIN','DRIVER','OPERATOR')),
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_users_role ON users(role);

CREATE TABLE charging_stations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(255) NOT NULL, address VARCHAR(255) NOT NULL,
  city VARCHAR(100) NOT NULL, latitude DECIMAL(10,7) NOT NULL, longitude DECIMAL(10,7) NOT NULL,
  price_per_kwh DECIMAL(10,2) NOT NULL, operating_hours VARCHAR(255) NOT NULL DEFAULT '24/7',
  available BOOLEAN NOT NULL DEFAULT TRUE, operator_id BIGINT NULL,
  CONSTRAINT fk_station_operator FOREIGN KEY(operator_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_station_city ON charging_stations(city);
CREATE INDEX idx_station_coordinates ON charging_stations(latitude,longitude);

CREATE TABLE chargers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(30) NOT NULL, connector_type VARCHAR(30) NOT NULL,
  power_kw DECIMAL(8,2) NOT NULL, status VARCHAR(20) NOT NULL CHECK (status IN ('AVAILABLE','OCCUPIED','OFFLINE','MAINTENANCE')),
  station_id BIGINT NOT NULL, CONSTRAINT fk_charger_station FOREIGN KEY(station_id) REFERENCES charging_stations(id) ON DELETE CASCADE,
  CONSTRAINT uk_station_charger_code UNIQUE(station_id,code)
);
CREATE INDEX idx_charger_status ON chargers(status);

CREATE TABLE bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, driver_id BIGINT NOT NULL, charger_id BIGINT NOT NULL,
  scheduled_at TIMESTAMP WITH TIME ZONE NOT NULL, status VARCHAR(20) NOT NULL CHECK (status IN ('BOOKED','CHARGING','COMPLETED','CANCELLED')),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(driver_id) REFERENCES users(id), FOREIGN KEY(charger_id) REFERENCES chargers(id)
);
CREATE INDEX idx_booking_driver ON bookings(driver_id);
CREATE INDEX idx_booking_start ON bookings(scheduled_at);

CREATE TABLE charging_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id BIGINT UNIQUE, driver_id BIGINT NOT NULL, charger_id BIGINT NOT NULL,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL, ended_at TIMESTAMP WITH TIME ZONE NULL, energy_kwh DECIMAL(10,3) NOT NULL DEFAULT 0,
  total_cost DECIMAL(10,2) NOT NULL DEFAULT 0, status VARCHAR(20) NOT NULL CHECK (status IN ('BOOKED','CHARGING','COMPLETED','CANCELLED')),
  FOREIGN KEY(booking_id) REFERENCES bookings(id), FOREIGN KEY(driver_id) REFERENCES users(id), FOREIGN KEY(charger_id) REFERENCES chargers(id)
);
CREATE INDEX idx_session_status ON charging_sessions(status);
CREATE INDEX idx_session_started ON charging_sessions(started_at);

CREATE TABLE payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id BIGINT NOT NULL UNIQUE, amount DECIMAL(10,2) NOT NULL,
  status VARCHAR(20) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(session_id) REFERENCES charging_sessions(id)
);

CREATE TABLE maintenance_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, charger_id BIGINT NOT NULL, description VARCHAR(255) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN', created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(charger_id) REFERENCES chargers(id)
);

CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, message VARCHAR(255) NOT NULL,
  read_flag BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE INDEX idx_notification_user ON notifications(user_id);
